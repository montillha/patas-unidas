// Detecta o tipo real da imagem pelos primeiros bytes (assinatura do arquivo), sem confiar no
// mimetype/extensão enviados pelo cliente, que podem ser forjados.
function detectarMime(buffer) {
  if (!buffer || buffer.length < 12) return null;

  if (buffer[0] === 0xff && buffer[1] === 0xd8 && buffer[2] === 0xff) return 'image/jpeg';

  const PNG = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];
  if (PNG.every((byte, i) => buffer[i] === byte)) return 'image/png';

  if (
    buffer.toString('ascii', 0, 4) === 'RIFF' &&
    buffer.toString('ascii', 8, 12) === 'WEBP'
  ) {
    return 'image/webp';
  }

  return null;
}

module.exports = { detectarMime };
